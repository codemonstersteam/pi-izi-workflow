// Формат накопленных ответов. Заведён потому, что прогон run-5 (F17) показал: пока источником
// чисел служит ФАЙЛ целиком, роль вправе протащить в критерий любое число из списка альтернатив
// собственного вопроса — её вопрос становится для неё источником фактов.

import test from "node:test"
import assert from "node:assert/strict"
import { answerEntry, newAnswers } from "./answers.mjs"

// --- answerEntry: тотальна, ветвей нет --------------------------------------------------------

test("запись ответа несёт вопрос и ответ раздельными строками", () => {
  assert.equal(answerEntry({ question: "предел?", text: "20" }), "- вопрос: предел?\n  ответ: 20\n")
})

// --- newAnswers: 1 happy + 1 ветвь (malformed) ------------------------------------------------

test("ответы разбираются в значения, а вопрос остаётся текстом роли", () => {
  const r = newAnswers("- вопрос: cap — 20 (alternatives: 50, 100)?\n  ответ: 20\n")
  assert.deepEqual(r.value.map((a) => a.text), ["20"])
})

test("пустой файл — пустой список, а не отказ: первый обмен идёт без ответов", () => {
  assert.deepEqual(newAnswers("").value, [])
})

test("вопрос без ответа — половина пары не факт и не вопрос", () => {
  assert.equal(newAnswers("- вопрос: предел?\n").error.cls, "malformed")
})

// F17 живьём: числа списка альтернатив принадлежат ВОПРОСУ и в значения не попадают.
test("числа из альтернатив вопроса не становятся источником", () => {
  const r = newAnswers("- вопрос: cap — 20 by default (alternatives: 50, 100)?\n  ответ: 20\n")
  assert.equal(r.value.map((a) => a.text).join(" ").includes("100"), false)
})
