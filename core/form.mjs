// --- Слои промпта ---------------------------------------------------------------------------------
//
// Роль и наряд — РАЗНЫЕ тексты с разными сроками жизни. Роль отвечает на «что мне вообще дозволено»
// и живёт в системном промпте (грузится раз за сессию). Наряд — «что именно сегодня», и он
// подставляется на КАЖДЫЙ вызов. Пункт, повторённый в обоих, оплачивается числом вызовов.

// НАБОР СЛОЁВ ЗАМКНУТ, и замкнут он ЗДЕСЬ. Раньше реестр знал только шесть системных имён, а
// steps/scope/role.md открывал седьмой слой ($START_LAW), izi.md и steps/brd/role.md — восьмой
// ($START_LINKS), и не краснело ничто: missingLayers судит нехватку, а избытка не видел никто.
// Слой, живущий в одной роли из трёх, перестаёт быть типизацией контекста и становится
// оформлением — набор слотов обязан быть ОДИН для всех ролей, иначе разметка не даёт модели
// того, ради чего заведена.
//
// LAW — не украшение и не половина ROLE: ROLE отвечает «кто ты», LAW — «что остаётся истиной,
// как бы ни сложился ход». Инварианты, разложенные по ROLE/FORBIDDEN/STRATEGY, читаются как
// частные оговорки, и роль торгуется с ними на первом же неудобном входе.
//
// TOOLS объявлен, но НЕ обязателен: слой существует для раннеров, которые не умеют карту путей в
// permission и печатают границу словами вместо права. В izi-pi-v2 сегодня (S11) такого раннера нет —
// права `gilb` несёт фронтматтер `tools:` роли напрямую, TOOLS в исходнике роли пуст, и быть не
// должен: руками он не пишется.
export const SYSTEM_LAYERS = ["ROLE", "LAW", "INPUT", "TOOLS", "STRATEGY", "FORBIDDEN", "OUTPUT_FORMAT", "EXAMPLE", "LINKS"]

// DOCUMENT и CONTENT — слои ВНУТРИ DATA: наряд объявляет каждый документ отдельно (путь + чем он
// является), и байты идут своим блоком. Их отсутствие в реестре и было дырой: линт на чужие слои
// покраснел бы на законном наряде.
export const USER_LAYERS = ["TASK", "DATA", "DOCUMENT", "CONTENT", "CONSTRAINTS", "OUTPUT"]

// Обязательны все системные слои, кроме TOOLS (его пишет установщик, см. выше). INPUT и EXAMPLE —
// не украшение:
// INPUT   — без него роль догадывается, что ей пришло, и идёт искать в репозиторий;
// EXAMPLE — сквозной прогон «вход → шаги → возврат» дешевле любого объяснения.
export const REQUIRED_SYSTEM = SYSTEM_LAYERS.filter((l) => l !== "TOOLS")
export const REQUIRED_USER = ["TASK", "DATA", "OUTPUT"]

// FUNCTION_CONTRACT: layersOf — какие слои промпта открыты маркером $START_<ИМЯ> в тексте
//   Input:        text — текст роли или наряда; тип не ограничен
//   Dependencies: —
//   Antecedent:   любое значение — undefined/null валидный вход, приводится к String(text || "")
//   Consequent:   success: string[] — имена слоёв в порядке появления маркера $START_<ИМЯ> в тексте;
//                          text отсутствует/пуст → String(text || "") = "" → возвращается [];
//                          маркер, встретившийся в тексте N раз, даёт ИМЯ N раз в результате —
//                          дубликаты не схлопываются, matchAll возвращает каждое совпадение по
//                          отдельности; парный $END_<ИМЯ> не проверяется — открытый без закрытия
//                          слой всё равно попадает в список, парность — забота missingLayers, не
//                          этой функции
//                 failure: нет — тотальна для любого входа
export function layersOf(text) {
  const found = []
  for (const m of String(text || "").matchAll(/\$START_([A-Z_]+)/g)) found.push(m[1])
  return found
}

// FUNCTION_CONTRACT: missingLayers — каких объявленных слоёв не хватает в тексте
//   Input:        text — текст роли или наряда; приводится к строке, тип не ограничен
//   Dependencies: required — реестр обязательных слоёв (REQUIRED_SYSTEM либо REQUIRED_USER)
//   Antecedent:   required — массив имён слоёв; text — любое значение
//   Consequent:   success: подмножество required, которого в тексте нет. Слой считается
//                          ОТСУТСТВУЮЩИМ, если верно хотя бы одно: нет маркера $START_<ИМЯ>
//                          либо нет закрывающего $END_<ИМЯ> — открытый и не закрытый слой
//                          неотличим от отсутствующего для того, кто читает текст сверху вниз
//                 failure: нет — тотальна на массиве
// Реестр приходит ЗАВИСИМОСТЬЮ, а не селектором. Прежняя сигнатура была (text, kind), где kind
// менял consequent, — это второй data-аргумент в одежде параметра (§3.2): функция делала два разных
// дела, выбирая между ними по строке. Теперь она делает одно, а какой набор обязателен, решает
// вызывающий, у которого этот факт и есть.
export function missingLayers(text, required) {
  const have = new Set(layersOf(text))
    return required.filter((l) => !have.has(l) || !String(text).includes(`$END_${l}`))
}

// FUNCTION_CONTRACT: extraLayers — какие слои текста реестром не объявлены
//   Input:        text — текст роли или наряда; приводится к строке, тип не ограничен
//   Dependencies: allowed — реестр допустимых слоёв (SYSTEM_LAYERS либо USER_LAYERS)
//   Antecedent:   allowed — массив имён слоёв; text — любое значение
//   Consequent:   success: имена открытых в тексте слоёв, которых нет в allowed, БЕЗ повторов, в
//                          порядке первого появления; текста нет/пуст → []
//                 failure: нет — тотальна
// Зеркало missingLayers, и заведено оно потому, что нехватка и избыток — РАЗНЫЕ дефекты: первый
// делает роль несобираемой, второй тихо расширяет грамматику промпта, и набор слотов перестаёт
// быть общим для всех ролей.
export function extraLayers(text, allowed) {
  const known = new Set(allowed)
  return [...new Set(layersOf(text))].filter((l) => !known.has(l))
}

// FUNCTION_CONTRACT: withoutExample — инструктивная часть промпта, без слоя EXAMPLE
//   Input:        text — текст роли; приводится к строке, тип не ограничен
//   Dependencies: —
//   Antecedent:   любое значение; парность маркеров не требуется
//   Consequent:   success: текст, из которого вырезаны все блоки $START_EXAMPLE..$END_EXAMPLE;
//                          блока нет либо он не закрыт → текст возвращается как есть
//                 failure: нет — тотальна
// Нужна там, где судится ФОРМУЛИРОВКА роли, а не её пример: язык примера задаёт наряд, не роль.
export function withoutExample(text) {
  return String(text || "").replace(/\$START_EXAMPLE[\s\S]*?\$END_EXAMPLE/g, "")
}

// FUNCTION_CONTRACT: cyrillicRatio — доля кириллицы среди букв текста
//   Input:        text — любой текст; приводится к строке, тип не ограничен
//   Dependencies: —
//   Antecedent:   любое значение
//   Consequent:   success: число 0..1 — кириллические буквы, делённые на все буквы;
//                          букв в тексте нет (пусто, цифры, разметка) → 0, а не деление на ноль
//                 failure: нет — тотальна
// Судится ДОЛЯ, а не наличие: одиночный термин, имя файла или цитата из чужого артефакта законны
// в англоязычном промпте, абзац прозы — нет. Порог объявлен в PROMPT_LANG, не здесь.
export function cyrillicRatio(text) {
  const s = String(text || "")
  const letters = s.match(/\p{L}/gu)
  if (!letters) return 0
  return letters.filter((c) => /[Ѐ-ӿ]/.test(c)).length / letters.length
}
