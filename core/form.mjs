//             missingLayers(text, required) — каких объявленных слоёв не хватает в тексте
//             extraLayers(text, allowed) — какие слои текста реестром не объявлены
//             withoutExample(text) — текст без слоя EXAMPLE (инструктивная часть промпта)
//             cyrillicRatio(text) — доля кириллицы среди букв текста
