// MODULE_CONTRACT: T4 — ОБРАЗЕЦ СУЩЕСТВУЕТ В ЭТОМ РЕПОЗИТОРИИ
// Purpose:    одно решение: назван ли образцом тот, кого можно грепнуть. Подшаг 2D ищет файлы
//             аналога ПО ТЕКСТУ и через них находит вызывающих — на eddi это 10 эталонных файлов
//             из 10 за полсекунды. Аналог с нулевым счётом даёт ноль файлов и молча обнуляет весь
//             этот улов.
// io:         none
// EXTERNAL_DEPENDENCY: steps/brd/brd.mjs::analogueTerm — грепаемая голова строки: имя до тире,
//             остальное объяснение. Отсутствие функции читается как `analogueTerm is not a function`.
// Invariants: ТОТАЛЕН. Таблицы попаданий нет — правило МОЛЧИТ: счёт брать неоткуда.
// Interface:  T4
//
// ПРЕДМЕТ СУДА — ОДНА СТРОКА, А НЕ АРТЕФАКТ. До 23.08.2026 подшаг судился четырьмя правилами по
// целому `.agent/brd.md`; три из них умерли вместе с тем, что модель перестала решать: `verdict`
// снят (его не читает ни один шаг полосы), R-строки и `subjects[]` собирает скрипт
// (`steps/brd/anchors/assemble.mjs`) КОПИЕЙ строк таблицы. Модель принимает ровно одно решение —
// какая существующая вещь служит образцом новой, — и врать ей больше нечем, кроме этой строки.
import { analogueTerm } from "../../brd.mjs"

// ОТСУТСТВИЕ ОБРАЗЦА — ЗАКОННЫЙ ВХОД, И ОН ОБЪЯВЛЯЕТСЯ. `none` это вывод роли о репозитории, а не
// пропуск строки, поэтому пишется словом — тот же приём, что `<failures found="no">`.
const DECLARED_ABSENT = /^none\b/i

// Заголовок строки. Роль пишет `analogue: <слово> — files <N>; <чем образец>`; правило судит
// ЗНАЧЕНИЕ, поэтому заголовок снимается здесь, а не у каждой ветви.
const HEAD = /^\s*analogue\s*:\s*/i

const low = (s) => String(s || "").toLowerCase()

// FUNCTION_CONTRACT: T4 — счёт образца в таблице попаданий
//   Input:        { line — строка ответа роли целиком: `analogue: <слово> — files <N>; <чем
//                   образец>`, либо null, если такой строки в ответе нет;
//                   hits — { слово: сколько файлов } из hitsOf / parseTable }
//   Dependencies: analogueTerm, DECLARED_ABSENT, HEAD
//   Antecedent:   таблица попаданий непуста. Нет таблицы — МОЛЧАНИЕ
//   Consequent:   success: [] — слово со счётом больше нуля ЛИБО объявленное отсутствие `none`;
//                 failure: один блокер — слово не названо · слова нет в таблице · у слова ноль;
//                 каждый называет оба выхода: слово со счётом либо объявленное отсутствие
//   Purity:       pure
//   Interface:    T4({ line, hits }) -> string[]
export function T4({ line = null, hits = null } = {}) {
  if (!hits || typeof hits !== "object") return []
  const words = Object.keys(hits)
  if (!words.length) return []

  const alive = words.filter((w) => Number(hits[w]) > 0).sort((a, b) => hits[b] - hits[a]).slice(0, 3)
  const exit = `Назови слово с НЕНУЛЕВЫМ счётом из таблицы попаданий${alive.length ? ` (например: ${alive.join(" · ")})` : ""} — «analogue: <слово> — files <N>; <чем он образец>», — либо объяви отсутствие: «analogue: none — <почему ничего похожего нет>»`

  // Строки нет, строка пуста, строка это один заголовок без значения — находка одна и та же:
  // слово не названо, судить нечего. Разводить их тремя блокерами значит писать роли три разных
  // наряда на одну правку.
  const value = String(line == null ? "" : line).replace(HEAD, "").trim()
  if (!value) return [`T4 analogue: слово не названо — по образцу чего делается работа, подшаг 2D спрашивает у этой строки. ${exit}`]
  if (DECLARED_ABSENT.test(value)) return []

  const term = analogueTerm(value)
  const key = words.find((w) => low(w) === low(term))
  if (!key) return [`T4 analogue: «${term}» — этого слова в таблице попаданий нет, значит его счёт по репозиторию никто не считал. ${exit}`]
  if (Number(hits[key]) === 0) return [`T4 analogue: «${term}» — в таблице попаданий у него 0 файлов: в этом репозитории такой вещи нет, и образцом она быть не может. ${exit}`]
  return []
}
