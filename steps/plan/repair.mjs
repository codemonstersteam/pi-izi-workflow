// MODULE_CONTRACT: repair — вердикт гардрейла, превращённый в ЗАДАЧУ наряда починки
// Purpose:    одно решение — как блокеры становятся списком дел. Наряд починки не говорит «почини
//             свой файл»: он говорит «сделай ровно эти три вещи», и каждая строка начинается с
//             АДРЕСА — строки или модуля, — чтобы роль не искала место правки по всему файлу.
// io:         none
// Invariants: ни одно слово блокера не выдумывается и не пересказывается: адрес выносится вперёд,
//             остальное копируется дословно. Гардрейл уже обязан был назвать выход
//             (standards/guardrail.md), и пересказ этот выход только испортил бы.
// Interface:  repairTask

// Адрес находки — то, по чему роль найдёт место правки: строка потока (`строка UC3/4`) или путь
// модуля. Блокеры пишутся по одному шаблону (`standards/guardrail.md`: код · элемент · выход), и
// адрес в них всегда стоит в начале.
const ADDRESS = [
  /^[A-Z]\d+\s+строка\s+(\S+)/,
  /^[A-Z]\d+\s+(?:в\s+)?<?[а-яё]*\s*(?:модуля?|модули)\s+([\w./-]+\.\w+)/i,
  /^[A-Z]\d+[^«]*?([\w./-]+\/[\w.-]+\.\w+)/,
  /^[A-Z]\d+\s+(?:значение\s+)?«([^»]+)»/,

  // АДРЕСА ШАГА 2. Блокеры BRD указывают не на файл, а на ТРЕБОВАНИЕ или на строку артефакта:
  // «R7: нет способа проверки», «subjects[] = 9; допустимо 3..8», «analogue пуст».
  // Без этих образцов наряд починки уходил бы вообще без адреса — то есть без того единственного,
  // ради чего он существует: роль искала бы место правки по всему документу.
  // Блокер подшага 2C (`steps/brd/anchors/judge/T4.mjs`) пишется по форме гардрейла: `<код>
  // <элемент>: <что не сходится> — <что написать вместо>`. Элемент и есть адрес: `subjects[]`,
  // `analogue` или номер требования — «T4 analogue: …».
  //
  // АДРЕС `open-questions` СНЯТ (тикет A06, 23.08.2026): строки с таким именем в артефакте больше
  // нет — его собирает скрипт из R-строк, `analogue:` и `subjects[]`, — а блокера на неё не пишет
  // никто с тех пор, как правило T1 удалено вместе с `verdict`.
  /^T\d+\s+([\w[\]-]+)\s*:/,
  /^(R\d+)\b/,                                      // R7: … и R12 [language-drift]: …
  /^(?:нет строки |нет )?(subjects\[\])/,            // subjects[] = 9 · нет subjects[]
  /^(?:нет строки |)(analogue)\b/,                   // analogue пуст

  // АДРЕС ПОДШАГА 2A. Блокер нормализации указывает на СТРОКУ ответа роли: «columns row 3: …»,
  // «clipped-value row 9: …». Строка и есть место правки, и без этого образца наряд починки
  // таблицы уходил бы без адреса — роль искала бы место по всем шестнадцати строкам.
  /^[a-z][a-z-]*\s+(row\s+\d+)\s*:/,
  // Находка ПРОХОДА ЧИСТКИ 2A адресует ПАРУ строк: дубль — это всегда две строки, и указать одну
  // из них значит послать роль чинить половину дефекта. «duplicate-row rows 1 and 17: …».
  /^[a-z][a-z-]*\s+(rows\s+\d+\s+and\s+\d+)\s*:/,
]

// FUNCTION_CONTRACT: repairTask — блокеры как нумерованный список дел
//   Input:        blockers — текст вердикта: по блокеру на строку, отступы допускаются
//   Dependencies: —
//   Antecedent:   любое значение; пустой вердикт даёт пустой список, а не отказ
//   Consequent:   success: { lines, count } — `lines` пронумерованы, у каждой впереди адрес правки,
//                          дальше ДОСЛОВНЫЙ текст блокера
//                 failure: none — тотальна
//   Purity:       pure
export function repairTask(blockers = "") {
  const items = String(blockers || "").split("\n").map((l) => l.trim()).filter(Boolean)
  const lines = items.map((text, k) => {
    // Адрес чистится от хвостовой пунктуации: блокер пишет «строка UC3/4:», и двоеточие в скобках
    // читается как часть адреса — роль пойдёт искать строку «UC3/4:», которой нет.
    const at = ADDRESS.map((re) => (text.match(re) || [])[1]).find(Boolean)?.replace(/[:,.;]+$/, "")
    return at ? `${k + 1}. [${at}] ${text}` : `${k + 1}. ${text}`
  })
  return Object.freeze({ lines: Object.freeze(lines), count: lines.length })
}
