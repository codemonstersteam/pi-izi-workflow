// Вердикт гардрейла, превращённый в задачу наряда починки: у каждой строки впереди АДРЕС правки,
// дальше дословный текст блокера.
//
// Модуль стоял без юнитов, а таблица `ADDRESS` — единственное место полосы, где решается, найдёт ли
// роль место правки вообще. Тикет A06 снял из неё адрес `open-questions` (строки с таким именем в
// артефакте шага 2 больше нет), и снимать образец из таблицы, у которой нет шва, значит снимать
// вслепую.
import test from "node:test"
import assert from "node:assert/strict"
import { repairTask } from "./repair.mjs"

// АДРЕСА ПОЛОСЫ, ПО ОДНОМУ НА ФОРМУ. Порядок в таблице — приоритет: адрес берётся первым
// совпавшим образцом, и потому строка `T4 analogue:` адресуется элементом, а не номером правила.
test("repairTask: у каждой находки впереди её адрес, текст блокера дословен", () => {
  const t = repairTask([
    "T4 analogue: слова «Glossaries» нет в таблице попаданий — возьми слово с ненулевым счётом",
    "analogue пуст — напиши одну строку `analogue: <слово> — чем образец`",
    "R7 нет способа проверки — допиши, чем требование унесено",
    "subjects[] = 9; допустимо 3..7",
    "columns row 3: колонок 5, а должно быть 4 — склей лишние в `values`",
    "F2 узел src/rest/Store.java не резолвится — назови путь из карты",
  ].join("\n"))

  assert.equal(t.count, 6)
  // Адрес читается до «] » — `subjects[]` носит свои скобки в имени, и жадный `[^\]]+` его обрежет.
  assert.deepEqual(t.lines.map((l) => (l.match(/^\d+\. \[(.+?)\] /) || [])[1]),
    ["analogue", "analogue", "R7", "subjects[]", "row 3", "src/rest/Store.java"])
  // Дословность: адрес ВЫНЕСЕН вперёд, а не вырезан из текста — гардрейл уже назвал выход, и
  // пересказ его испортил бы (standards/guardrail.md).
  assert.match(t.lines[0], /^1\. \[analogue\] T4 analogue: слова «Glossaries» нет в таблице попаданий — возьми слово с ненулевым счётом$/)
})

// ХВОСТОВАЯ ПУНКТУАЦИЯ НЕ ЧАСТЬ АДРЕСА: блокер пишет «строка UC3/4:», и двоеточие внутри скобок
// отправило бы роль искать строку «UC3/4:», которой нет. Адреса нет вовсе — строка всё равно
// нумеруется: список дел без одного адреса лучше, чем потерянная находка.
test("repairTask: адрес чистится от хвостовой пунктуации, а без адреса остаётся голая нумерация", () => {
  const t = repairTask("F2 строка UC3/4: узел не резолвится\nчто-то пошло не так вообще")
  assert.equal(t.lines[0], "1. [UC3/4] F2 строка UC3/4: узел не резолвится")
  assert.equal(t.lines[1], "2. что-то пошло не так вообще")
})

// МОЛЧАНИЕ НА ОТСУТСТВУЮЩЕМ ОПЕРАНДЕ. Вердикта нет — список пуст, а не отказ: наряд починки
// зовут только с красным вердиктом, и пустой вердикт здесь означает «судить нечего».
test("repairTask МОЛЧАНИЕ: вердикта нет — пустой список дел, а не исключение", () => {
  for (const empty of ["", "   \n\n  ", undefined, null]) {
    const t = repairTask(empty)
    assert.equal(t.count, 0)
    assert.deepEqual(t.lines, [])
  }
})
